CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA extensions;

CREATE TABLE IF NOT EXISTS admin (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  name VARCHAR(255) NOT NULL DEFAULT 'Administrator',
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS parent (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  name VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS student (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id VARCHAR(50) NOT NULL UNIQUE,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  grade_level VARCHAR(20),
  section VARCHAR(20),
  parent_id INTEGER NOT NULL REFERENCES parent(id) ON DELETE CASCADE,
  parent_email VARCHAR(255) NOT NULL,
  face_encoding TEXT,
  face_embedding extensions.vector(128),
  image_path VARCHAR(255),
  status VARCHAR(20) NOT NULL DEFAULT 'NOT_IN_CAMPUS',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS entry_exit_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES student(id) ON DELETE CASCADE,
  event_type VARCHAR(5) NOT NULL CHECK (event_type IN ('ENTRY', 'EXIT')),
  timestamp TIMESTAMPTZ NOT NULL DEFAULT now(),
  location VARCHAR(255) NOT NULL DEFAULT 'Main Gate',
  confidence_score NUMERIC(5, 2)
);
CREATE INDEX IF NOT EXISTS idx_entry_exit_student_timestamp
  ON entry_exit_log (student_id, timestamp DESC);

CREATE TABLE IF NOT EXISTS activity_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_role VARCHAR(10) NOT NULL CHECK (actor_role IN ('admin', 'parent', 'system')),
  actor_id INTEGER,
  actor_email VARCHAR(255),
  action VARCHAR(100) NOT NULL,
  entity_type VARCHAR(50),
  entity_id VARCHAR(64),
  parent_id INTEGER REFERENCES parent(id) ON DELETE SET NULL,
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_activity_actor_time
  ON activity_log (actor_role, actor_id, created_at);
CREATE INDEX IF NOT EXISTS idx_activity_parent_time
  ON activity_log (parent_id, created_at);
CREATE INDEX IF NOT EXISTS idx_activity_entity
  ON activity_log (entity_type, entity_id);

CREATE TABLE IF NOT EXISTS app_message (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_role VARCHAR(6) NOT NULL CHECK (sender_role IN ('admin', 'parent')),
  sender_id INTEGER NOT NULL,
  sender_email VARCHAR(255) NOT NULL,
  receiver_role VARCHAR(6) NOT NULL CHECK (receiver_role IN ('admin', 'parent')),
  receiver_id INTEGER NOT NULL,
  receiver_email VARCHAR(255) NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_message_conversation
  ON app_message (sender_role, sender_id, receiver_role, receiver_id, created_at);
CREATE INDEX IF NOT EXISTS idx_message_reverse
  ON app_message (receiver_role, receiver_id, sender_role, sender_id, created_at);

