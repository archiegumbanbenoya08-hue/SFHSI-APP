CREATE SCHEMA IF NOT EXISTS legacy_scmcies;

CREATE TABLE IF NOT EXISTS legacy_scmcies.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  password TEXT NOT NULL,
  name VARCHAR(255) NOT NULL,
  user_type VARCHAR(10) NOT NULL DEFAULT 'parent'
    CHECK (user_type IN ('admin', 'parent')),
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_legacy_scmcies_users_email
  ON legacy_scmcies.users (email);
CREATE INDEX IF NOT EXISTS idx_legacy_scmcies_users_type
  ON legacy_scmcies.users (user_type);

CREATE TABLE IF NOT EXISTS legacy_scmcies.students (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(255) NOT NULL,
  grade VARCHAR(50) NOT NULL,
  parent_emails TEXT NOT NULL,
  face_data TEXT,
  face_embedding extensions.vector(128),
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_legacy_scmcies_students_id
  ON legacy_scmcies.students (student_id);
CREATE INDEX IF NOT EXISTS idx_legacy_scmcies_students_name
  ON legacy_scmcies.students (name);
CREATE INDEX IF NOT EXISTS idx_legacy_scmcies_students_grade
  ON legacy_scmcies.students (grade);

ALTER TABLE legacy_scmcies.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE legacy_scmcies.students ENABLE ROW LEVEL SECURITY;
